/** Default looks that suit each take, used until the player changes hair or skin. */
export const TAKE_LOOKS: Record<TakeId, Look> = {
  lean: DEFAULT_LOOK,
  street: { ...DEFAULT_LOOK, hair: 'black' },
  hunter: { ...DEFAULT_LOOK, hair: 'silver' },
};

/** One frame of a take, wearing a look's hair and skin. */
export function drawTake(id: TakeId, look: Look, frame: ClipFrame): Grid {
  const t = TAKES[id],
    H = HAIR[look.hair],
    S = SKIN[look.skin],
    ink: Record<string, string> = {
      K: '#16111e',
      a: H[0], b: H[1], c: H[2],
      d: S[0], e: S[1], f: S[2],
      g: '#5a2a1c', y: '#fff6ea', u: '#a85a4a', o: '#6a4a5a',
      ...t.outfit,
    },
    bob = frame.bob ?? 0,
    g = grid(64);
  t.rows.forEach((row, y) =>
    [...row].forEach((ch, x) => {
      const yy = y < t.waist ? y + bob : y;
      if (ink[ch] && yy < 64) g[yy][x + 16] = ink[ch];
    }),
  );
  return g;
}
